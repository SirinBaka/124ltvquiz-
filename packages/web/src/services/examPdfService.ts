export function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function unescapeMathDelimiters(expr: string): string {
  return expr
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");
}

function renderRichStringToHtml(raw: string): string {
  if (!raw) return "";

  let text = normalizeScientificText(raw);
  text = text.replace(/\\?\[\/?BOLD\\?\]/gi, "");
  text = text.replace(/\\?\[\/?(?:RED|UNDERLINE)\\?\]/gi, "");
  text = text.replace(/\\([._[\]])/g, "$1");

  // Preserve markdown images (including optional title) before HTML escaping
  const imagePlaceholders: string[] = [];
  text = text.replace(/!\[(.*?)\]\(([^\s)]+)(?:\s+"[^"]*")?\)/g, (_m, alt, src) => {
    const idx = imagePlaceholders.length;
    imagePlaceholders.push(
      `<img src="${escapeHtml(src)}" alt="${escapeHtml(alt || "image")}" class="q-inline-img" />`,
    );
    return `@@IMG_${idx}@@`;
  });

  // Escape HTML first so plain < or > doesn't break HTML tags
  let html = escapeHtml(text);

  // Restore safe inline <sub> and <sup> tags generated by document parsers
  html = html
    .replace(/&lt;sub&gt;([\s\S]*?)&lt;\/sub&gt;/gi, "<sub>$1</sub>")
    .replace(/&lt;sup&gt;([\s\S]*?)&lt;\/sup&gt;/gi, "<sup>$1</sup>");

  // Formatting tags: match outer $...$ pairs before plain [...] so inner math stays intact
  const azotaTags: Array<{ tag: string; open: string; close: string }> = [
    { tag: "b", open: "<strong>", close: "</strong>" },
    { tag: "i", open: "<em>", close: "</em>" },
    { tag: "u", open: "<u>", close: "</u>" },
    { tag: "red", open: '<span class="text-red">', close: "</span>" },
    { tag: "blue", open: '<span class="text-blue">', close: "</span>" },
  ];
  for (const { tag, open, close } of azotaTags) {
    html = html.replace(
      new RegExp(`\\[!${tag}:\\$([\\s\\S]*?)\\$\\]`, "gi"),
      `${open}$1${close}`,
    );
    html = html.replace(
      new RegExp(`\\[!${tag}:((?:[^\\[\\]]|\\[[^\\]]*\\])*)\\]`, "gi"),
      `${open}$1${close}`,
    );
  }
  html = html.replace(/\*\*([\s\S]*?)\*\*/g, "<strong>$1</strong>");

  // Block math $$...$$ or \[...\]
  html = html.replace(
    /\$\$([\s\S]+?)\$\$|\\\[([\s\S]+?)\\\]/g,
    (match, math1, math2) => {
      const expr = unescapeMathDelimiters(math1 || math2 || "");
      try {
        return katex.renderToString(expr, {
          displayMode: true,
          throwOnError: false,
          strict: false,
        });
      } catch {
        return match;
      }
    },
  );

  // Inline math $...$ or \(...\)
  html = html.replace(
    /\$([^\n$]+?)\$|\\\(([\s\S]+?)\\\)/g,
    (match, math1, math2) => {
      const expr = unescapeMathDelimiters(math1 || math2 || "");
      try {
        return katex.renderToString(expr, {
          displayMode: false,
          throwOnError: false,
          strict: false,
        });
      } catch {
        return match;
      }
    },
  );

  // Bare \ce{...} chemical equations if not inside $...$
  html = html.replace(/\\ce\{([^{}]+(?:\{[^{}]*\}[^{}]*)*)\}/g, (match, chemExpr) => {
    try {
      return katex.renderToString(`\\ce{${chemExpr}}`, {
        displayMode: false,
        throwOnError: false,
        strict: false,
      });
    } catch {
      return match;
    }
  });

  // Restore images and line breaks
  html = html.replace(/@@IMG_(\d+)@@/g, (_m, idxStr) => {
    return imagePlaceholders[Number(idxStr)] || "";
  });
  html = html.replace(/\n/g, "<br />");

  return html;
}

function isInlineImageBlock(
  blocks: readonly ContentBlock[],
  idx: number,
  forceInline?: boolean,
): boolean {
  if (forceInline) return true;
  const prev = idx > 0 ? blocks[idx - 1] : null;
  const next = idx + 1 < blocks.length ? blocks[idx + 1] : null;

  const prevIsInlineText =
    prev !== null &&
    (prev.type === "math" ||
      (prev.type === "text" &&
        prev.content.trim().length > 0 &&
        !/[:\n]\s*$/.test(prev.content)));
  const nextIsInlineContinuation =
    next !== null &&
    (next.type === "math" ||
      (next.type === "text" &&
        /^\s*(?:[.,;?!)\]=+\-*/]|[a-zàáảãạăắằẳẵặâấầẩẫậèéẻẽẹêếềểễệđìíỉĩịòóỏõọôốồổỗộơớờởỡợùúủũụưứừửữựỳýỷỹỵ])/i.test(
          next.content,
        )));

  return prevIsInlineText || nextIsInlineContinuation;
}

export function renderContentBlocksToHtml(
  blocks: readonly ContentBlock[],
  options?: { inlineImages?: boolean },
): string {
  if (!blocks || blocks.length === 0) return "";
  return blocks
    .map((block, idx) => {
      if (block.type === "image") {
        const inline = isInlineImageBlock(blocks, idx, options?.inlineImages);
        if (inline) {
          return `<img src="${escapeHtml(block.content)}" alt="${escapeHtml(block.alt || "Hình minh họa")}" class="q-inline-img" />`;
        }
        return `<div class="q-img-wrap"><img src="${escapeHtml(block.content)}" alt="${escapeHtml(block.alt || "Hình minh họa")}" class="q-img" /></div>`;
      }
      if (block.type === "math") {
        const expr = block.content.trim();
        const wrapped = expr.startsWith("$") ? expr : `$${expr}$`;
        return renderRichStringToHtml(wrapped);
      }
      return renderRichStringToHtml(block.content);
    })
    .join(" ");
}

function getOptionPlainLength(q: Question): number {
  let maxLen = 0;
  for (const opt of q.options || []) {
    const hasImg = opt.content.some((b) => b.type === "image");
    if (hasImg) return 999;
    const len = opt.content.map((b) => b.content).join(" ").trim().length;
    if (len > maxLen) maxLen = len;
  }
  return maxLen;
}

function blocksToRawEditableText(blocks: readonly ContentBlock[] = []): string {
  return blocks
    .filter((b) => b.type !== "image")
    .map((b) => (b.type === "math" && !b.content.startsWith("$") ? `$${b.content}$` : b.content))
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();
}

