export function renderExamSheetInnerHtml(
  variant: ExamVariant,
  options: ExamRenderOptions,
): string {
  const safeBase = escapeHtml(options.examTitle || options.baseName || "ĐỀ KIỂM TRA");
  const safeSchool = escapeHtml(options.schoolName || "ĐỀ THI TRẮC NGHIỆM KHÁCH QUAN");
  const duration = options.durationMinutes || 45;
  const safeCode = escapeHtml(variant.examCode);

  let currentSection = "";
  let questionsHtml = "";

  const isEditable = Boolean(options.interactiveEdit);

  variant.questions.forEach((q, idx) => {
    const sec = (q.sectionTitle || "").trim();
    if (sec && sec !== currentSection) {
      currentSection = sec;
      questionsHtml += `<div class="section-heading">${escapeHtml(sec)}</div>`;
    }

    const kind = classifyQuestion(q);
    const promptHtml = renderContentBlocksToHtml(q.question);
    const rawPrompt = escapeHtml(blocksToRawEditableText(q.question));
    let bodyHtml = "";

    if (kind === "short_answer") {
      const ans = variant.answerKey[idx]?.shuffledAnswer;
      bodyHtml = `<div class="short-answer-box">Trả lời: ........................................................................</div>`;
      if (options.showAnswers && ans && ans !== "Chưa có") {
        bodyHtml += `<div class="short-answer-reveal">Đáp án: ${escapeHtml(ans)}</div>`;
      }
    } else {
      const maxLen = getOptionPlainLength(q);
      const colClass =
        options.columnsMode && options.columnsMode !== "auto"
          ? `cols-${options.columnsMode}`
          : kind === "true_false_multiple" || maxLen > 38
            ? "cols-1"
            : maxLen <= 16 && (q.options?.length || 0) === 4
              ? "cols-4"
              : "cols-2";

      const optsHtml = (q.options || [])
        .map((opt) => {
          const isCorrect = q.correctAnswer?.includes(opt.id);
          const optCls =
            options.showAnswers && isCorrect
              ? "option-item option-correct"
              : "option-item";
          const suffix =
            kind === "true_false_multiple" ? ")" : ".";
          const tfBadge =
            options.showAnswers && kind === "true_false_multiple"
              ? ` <span style="font-size:10pt;">[${isCorrect ? "Đúng" : "Sai"}]</span>`
              : "";
          const rawOpt = escapeHtml(blocksToRawEditableText(opt.content));
          const optTextBlocks = opt.content.filter((b) => b.type !== "image");
          const optImgBlocks = opt.content.filter((b) => b.type === "image");
          const labelSpan = isEditable
            ? `<span class="option-label opt-label-clickable" title="Nhấn để chọn/đổi đáp án đúng" data-click-opt="1">${escapeHtml(opt.label)}${suffix}</span>`
            : `<span class="option-label">${escapeHtml(opt.label)}${suffix}</span>`;
          const textSpan = isEditable
            ? `<span class="editable-field" contenteditable="true" data-opt-text="1" data-raw="${rawOpt}">${renderContentBlocksToHtml(optTextBlocks)}</span>${optImgBlocks.length > 0 ? renderContentBlocksToHtml(optImgBlocks, { inlineImages: true }) : ""}`
            : renderContentBlocksToHtml(opt.content, { inlineImages: true });

          return `<div class="${optCls}" data-q-idx="${idx}" data-opt-id="${escapeHtml(opt.id)}" data-is-tf="${kind === "true_false_multiple"}">${labelSpan} ${textSpan}${tfBadge}</div>`;
        })
        .join("");

      bodyHtml = `<div class="options-grid ${colClass}">${optsHtml}</div>`;
    }

    const qTextBlocks = q.question.filter((b) => b.type !== "image");
    const qImgBlocks = q.question.filter((b) => b.type === "image");
    const promptSpan = isEditable
      ? `<span class="editable-field" contenteditable="true" data-q-prompt="${idx}" data-raw="${rawPrompt}">${renderContentBlocksToHtml(qTextBlocks)}</span>`
      : promptHtml;
    const promptImagesHtml =
      isEditable && qImgBlocks.length > 0
        ? renderContentBlocksToHtml(qImgBlocks)
        : "";

    questionsHtml += `
      <div class="question-block">
        <div class="question-prompt"><span class="q-num">Câu ${idx + 1}.</span> ${promptSpan}${promptImagesHtml}</div>
        ${bodyHtml}
      </div>
    `;
  });

  let answerSectionHtml = "";
  if (options.showAnswers && variant.answerKey.length > 0) {
    const rows = variant.answerKey
      .map(
        (a) =>
          `<tr><td>${a.questionIndex}</td><td>${a.originalIndex}</td><td><strong>${escapeHtml(a.shuffledAnswer)}</strong></td></tr>`,
      )
      .join("");
    answerSectionHtml = `
      <div class="answer-section">
        <div class="answer-heading">Đáp án Mã đề ${safeCode}</div>
        <table class="answer-table">
          <thead><tr><th>Câu mới</th><th>Câu gốc</th><th>Đáp án</th></tr></thead>
          <tbody>${rows}</tbody>
        </table>
      </div>
    `;
  }

  const schoolAttr = isEditable
    ? 'contenteditable="true" data-header-field="schoolName"'
    : "";
  const titleAttr = isEditable
    ? 'contenteditable="true" data-header-field="examTitle"'
    : "";
  const durationSpan = isEditable
    ? `<span class="editable-field" contenteditable="true" data-header-field="durationMinutes" data-raw="${duration}">${duration}</span>`
    : String(duration);

  return `
    <div class="a4-sheet">
      <div class="exam-header">
        <div class="header-left">
          <div class="org-name ${isEditable ? "editable-field" : ""}" ${schoolAttr} data-raw="${safeSchool}">${safeSchool}</div>
          <div class="exam-sub">Đề thi gồm ${variant.questions.length} câu hỏi</div>
        </div>
        <div class="header-right">
          <div class="exam-title ${isEditable ? "editable-field" : ""}" ${titleAttr} data-raw="${safeBase}">${safeBase}</div>
          <div class="exam-sub">Thời gian làm bài: ${durationSpan} phút (không kể thời gian phát đề)</div>
          <div class="code-badge">Mã đề: ${safeCode}</div>
        </div>
      </div>

      <div class="student-line">
        <span>Họ và tên thí sinh: ........................................................................</span>
        <span>Số báo danh: .......................</span>
      </div>

      <div class="questions-container">${questionsHtml}</div>

      <div class="exam-footer">---------- HẾT ----------</div>
      ${answerSectionHtml}
    </div>
  `;
}

